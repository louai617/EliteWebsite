import type { Metadata } from "next";
import Image from "next/image";
import Link from "next/link";
import { notFound } from "next/navigation";
import { ArrowLeft } from "lucide-react";
import { requireUser } from "@/lib/auth/session";
import { renderContractHtml } from "@/lib/contract-format";
import { formatDateTime } from "@/lib/format";
import { getContract } from "@/services/contracts";
import { COMPANY } from "@/services/email-templates";
import { PrintButton } from "@/components/contracts/print-button";

export const metadata: Metadata = { title: "Contract" };

export default async function ContractPage({ params }: PageProps<"/contracts/[id]">) {
  const user = await requireUser();
  const { id } = await params;
  const contract = await getContract(user, id);
  if (!contract) notFound();

  return (
    <>
      <div className="sticky top-0 z-10 border-b bg-background/95 backdrop-blur print:hidden">
        <div className="mx-auto flex max-w-[210mm] items-center justify-between gap-3 px-4 py-3">
          <Link href={`/deals/${contract.dealId}`} className="inline-flex items-center gap-1.5 text-sm text-muted-foreground hover:text-foreground">
            <ArrowLeft className="size-4" /> {contract.deal.reference}
          </Link>
          <div className="flex items-center gap-3">
            <span className="hidden text-xs text-muted-foreground sm:inline">
              {contract.reference} · {contract.templateName} v{contract.templateVersion} · {formatDateTime(contract.createdAt)}
              {contract.createdBy ? ` · ${contract.createdBy.name}` : ""}
            </span>
            <PrintButton />
          </div>
        </div>
      </div>

      <article className="contract-sheet mx-auto my-8 max-w-[210mm] bg-white px-[18mm] py-[16mm] shadow-sm print:my-0 print:max-w-none print:p-0 print:shadow-none">
        <header className="mb-8 flex items-end justify-between border-b-2 border-[#b98f42] pb-4">
          <Image src="/email-logo.png" alt="ELITE Real Estate" width={200} height={51} priority />
          <div className="text-right text-[11px] leading-4 text-neutral-500">
            <p className="font-semibold text-neutral-800">{contract.reference}</p>
            <p>{COMPANY.address}</p>
            <p>{COMPANY.phone}</p>
          </div>
        </header>
        {/* renderContractHtml escapes everything and only adds headings, bold, lists and paragraphs. */}
        <div className="contract-body" dangerouslySetInnerHTML={{ __html: renderContractHtml(contract.body) }} />
        <footer className="mt-12 border-t pt-3 text-[10px] text-neutral-400">
          {contract.reference} · Generated by ELITE Real Estate from “{contract.templateName}” (version {contract.templateVersion}).
        </footer>
      </article>
    </>
  );
}
